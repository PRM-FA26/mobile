/// Counts words in a string.
///
/// Mirrors `countWords()` from `fe-web-novel/src/lib/utils.ts`.
int countWords(String str) {
  if (str.isEmpty) return 0;
  return str.trim().split(RegExp(r'\s+')).where((s) => s.isNotEmpty).length;
}

/// Vietnamese relative time formatting.
///
/// Mirrors `formatDate()` from History page.
String formatRelativeTime(DateTime date) {
  final now = DateTime.now();
  final diff = now.difference(date);

  if (diff.inMinutes < 1) return 'Vừa xong';
  if (diff.inMinutes < 60) return '${diff.inMinutes} phút trước';
  if (diff.inHours < 24) return '${diff.inHours} giờ trước';
  if (diff.inDays < 7) return '${diff.inDays} ngày trước';
  return DateFormat('dd/MM/yyyy').format(date);
}

/// Formats a number as Vietnamese shorthand.
///
/// 1234 → "1.2K", 1234567 → "1.2M"
String formatCompactNumber(int value) {
  if (value >= 1000000) {
    return '${(value / 1000000).toStringAsFixed(1)}M';
  }
  if (value >= 1000) {
    return '${(value / 1000).toStringAsFixed(1)}K';
  }
  return value.toString();
}

/// Format xu (coin) value with thousands separator.
String formatXu(int amount) {
  return NumberFormat('#,###', 'vi').format(amount);
}
